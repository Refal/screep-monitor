#!/usr/bin/env node
// Renders public/firebase-config.js from config supplied out-of-band, so the
// real API key never lives in the repo. Source, in order:
//   1. FIREBASE_WEB_CONFIG env var (JSON string) — the CI path, see
//      .github/workflows/deploy.yml
//   2. web-config.local.json in the repo root — the local dev path
//      (gitignored; see README "Local dashboard with real data")
// Run via `npm run gen:config`.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const outPath = new URL("../public/firebase-config.js", import.meta.url);

function loadConfig() {
    if (process.env.FIREBASE_WEB_CONFIG) {
        return JSON.parse(process.env.FIREBASE_WEB_CONFIG);
    }
    try {
        return JSON.parse(readFileSync(`${root}web-config.local.json`, "utf8"));
    } catch (err) {
        if (err.code !== "ENOENT") throw err;
        console.error(
            "No Firebase web config found. Provide one of:\n" +
            "  - FIREBASE_WEB_CONFIG env var (JSON string), or\n" +
            "  - web-config.local.json in the repo root (gitignored)\n" +
            'Shape: {"apiKey":"...","authDomain":"...","projectId":"...","appCheckSiteKey":"..."}'
        );
        process.exit(1);
    }
}

const cfg = loadConfig();
for (const key of ["apiKey", "authDomain", "projectId"]) {
    if (!cfg[key]) {
        console.error(`Firebase web config is missing required field "${key}".`);
        process.exit(1);
    }
}

const body = `// GENERATED by scripts/gen-web-config.mjs — do not edit by hand, and do not
// commit real values here. Source: FIREBASE_WEB_CONFIG (CI) or
// web-config.local.json (local dev). See README for setup.
export const firebaseConfig = {
    apiKey: ${JSON.stringify(cfg.apiKey)},
    authDomain: ${JSON.stringify(cfg.authDomain)},
    projectId: ${JSON.stringify(cfg.projectId)},${cfg.appCheckSiteKey ? `
    appCheckSiteKey: ${JSON.stringify(cfg.appCheckSiteKey)},` : ""}
};
`;

writeFileSync(outPath, body);
console.log(`Wrote ${fileURLToPath(outPath)}`);
